function loadOnLessons() {
  const lessons = JSON.parse(
    readFileSync(join(root, 'js/grade4Lessons.js'), 'utf8')
      .replace(/^[\s\S]*?export const GRADE4_LESSONS = /, '')
      .replace(/;\s*$/, ''),
  );
  const translations = JSON.parse(
    readFileSync(join(root, 'js/grade4Translations.js'), 'utf8')
      .replace(/^[\s\S]*?export const GRADE4_TRANSLATIONS = /, '')
      .replace(/;\s*$/, ''),
  );
  return lessons
    .filter((lesson) => lesson.id.startsWith('grade4-on-'))
    .map((lesson) => ({
      ...lesson,
      translations: translations[lesson.id],
    }));
}

const extras = loadOnLessons();

const all = [
  ...UNITS.map(({ translations, ...lesson }) => ({
    ...lesson,
    level: 'a1',
    topic: 'grade4',
  })),
  ...extras.map(({ translations, ...lesson }) => lesson),
];

const trans = Object.fromEntries([
  ...UNITS.map((unit) => [unit.id, unit.translations]),
  ...extras.map((lesson) => [lesson.id, lesson.translations]),
]);

for (const lesson of all) {
  const vi = trans[lesson.id];
  if (!vi || vi.length !== lesson.sentences.length) {
    throw new Error(`${lesson.id}: en=${lesson.sentences.length} vi=${vi?.length ?? 0}`);
  }
}

writeFileSync(
  join(root, 'js/grade4Lessons.js'),
  `/** Global Success Grade 4 — 20 textbook units */\nexport const GRADE4_LESSONS = ${JSON.stringify(all, null, 2)};\n`,
);
writeFileSync(
  join(root, 'js/grade4Translations.js'),
  `/** Global Success Grade 4 translations */\nexport const GRADE4_TRANSLATIONS = ${JSON.stringify(trans, null, 2)};\n`,
);

console.log(`Wrote ${UNITS.length} units + ${extras.length} extras`);
